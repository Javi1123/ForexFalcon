/** Código ISO de dos letras → emoji de bandera (ES → 🇪🇸). */
export function getFlagEmoji(codigoIso) {
  return String.fromCodePoint(
    ...codigoIso.toUpperCase().split('').map(function (c) { return 127397 + c.charCodeAt(0); })
  );
}
